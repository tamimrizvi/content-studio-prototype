// Generates src/styles/tokens.css and src/styles/tokens.generated.ts from
// tokens/tokens.json (Figma variables export). Run with `npm run tokens`.
//
// Layers:
//   Primitives  -> raw palette + scale            (CSS variables only)
//   Alias       -> neutral/brand/…, radius, space (CSS variables only)
//   Semantic    -> surface / border / content / fill, light + dark
//   Typography  -> family, size, line height, letter spacing
//
// Only the Semantic colours are exposed as Tailwind colour utilities, so
// components cannot reach for a primitive or alias colour by accident.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = JSON.parse(readFileSync(resolve(root, "tokens/tokens.json"), "utf8"));

const primitives = src["Primitives/Mode 1"];
const alias = src["Alias/Mode 1"];
const light = src["Semantic/Light"];
const dark = src["Semantic/Dark"];
const typography = src["Typography /Mode 1"];

const slug = (s) => String(s).trim().toLowerCase().replace(/\s+/g, "-");

function* leaves(node, path = []) {
  if (node && typeof node === "object" && "value" in node && "type" in node) {
    yield [path, node];
    return;
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    yield* leaves(child, [...path, key]);
  }
}

/** CSS variable name for an alias-collection path. */
function aliasVar(path) {
  const [group, ...rest] = path.map(slug);
  if (group === "roundness") return `--roundness-${rest.join("-").replace(/^radius-/, "")}`;
  if (group === "spacing") return `--space-${rest.join("-").replace(/^spacing-/, "")}`;
  if (group === "stroke-width") return `--stroke-${rest.join("-")}`;
  return `--${[group, ...rest].join("-")}`;
}
const primitiveVar = (path) => `--${path.map(slug).join("-")}`;
const semanticVar = (path) => `--${path.map(slug).join("-")}`;

// Reference lookup: "{neutral.white}" -> "--neutral-white". Alias wins over
// primitives, matching how the Figma collections reference each other.
const refs = new Map();
for (const [path] of leaves(primitives)) refs.set(path.join("."), primitiveVar(path));
for (const [path] of leaves(alias)) refs.set(path.join("."), aliasVar(path));

function ref(token) {
  const name = refs.get(token);
  if (!name) throw new Error(`Unknown token reference {${token}}`);
  return `var(${name})`;
}

function resolveValue(value, type) {
  if (typeof value === "number") return type === "number" ? `${value}px` : String(value);
  const rgba = /^rgba\(\{([^}]+)\},\s*([\d.]+)\)$/.exec(value);
  if (rgba) {
    const pct = Math.round(Number(rgba[2]) * 100);
    return `color-mix(in srgb, ${ref(rgba[1])} ${pct}%, transparent)`;
  }
  const single = /^\{([^}]+)\}$/.exec(value);
  if (single) return ref(single[1]);
  return value;
}

const decl = (name, value) => `  ${name}: ${value};`;
const out = [];
out.push("/* GENERATED by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit. */", "");

// ── Primitives + alias ───────────────────────────────────────────────────
out.push(":root {", "  /* Primitives */");
for (const [path, t] of leaves(primitives)) out.push(decl(primitiveVar(path), resolveValue(t.value, t.type)));
out.push("", "  /* Alias */");
for (const [path, t] of leaves(alias)) out.push(decl(aliasVar(path), resolveValue(t.value, t.type)));

// ── Typography ───────────────────────────────────────────────────────────
out.push("", "  /* Typography */");
const weights = { regular: 400, medium: 500, semibold: 600, bold: 700 };
const typeStyles = new Map(); // "body-sm" -> true
for (const [path, t] of leaves(typography)) {
  const [group, ...rest] = path.map(slug);
  if (group === "font-family") {
    out.push(decl(`--font-family-${rest[0]}`, `var(--font-dm-sans, "${t.value}"), ui-sans-serif, system-ui, sans-serif`));
  } else if (group === "font-weight") {
    out.push(decl(`--font-weight-${rest[0]}`, weights[rest[0]] ?? 400));
  } else {
    // Figma left stray "label/xl 2…5" duplicates in the export; skip them.
    if (/\s/.test(path[path.length - 1])) continue;
    out.push(decl(`--${group}-${rest.join("-")}`, resolveValue(t.value, "number")));
    if (group === "font-size") typeStyles.set(rest.join("-"), rest[0]);
  }
}

// ── Semantic, light (default) and dark ───────────────────────────────────
const semanticNames = [];
out.push("", "  /* Semantic: light */");
for (const [path, t] of leaves(light)) {
  semanticNames.push(path.map(slug));
  out.push(decl(semanticVar(path), resolveValue(t.value, t.type)));
}
out.push("}", "", ".dark {", "  /* Semantic: dark */");
for (const [path, t] of leaves(dark)) out.push(decl(semanticVar(path), resolveValue(t.value, t.type)));
out.push("}", "");

// ── Tailwind theme ───────────────────────────────────────────────────────
out.push("@theme inline {", "  /* Colours: semantic tokens only. */", "  --color-*: initial;");
for (const p of semanticNames) out.push(decl(`--color-${p.join("-")}`, `var(--${p.join("-")})`));
out.push("", "  /* Radius: roundness tokens (rounded-1 … rounded-12). */", "  --radius-*: initial;");
for (const [path] of leaves(alias.roundness)) {
  const n = slug(path[0]).replace(/^radius-/, "");
  if (n === "none" || n === "full") continue; // Tailwind's rounded-none / rounded-full already match
  out.push(decl(`--radius-${n}`, `var(--roundness-${n})`));
}
out.push("", "  /* Type: use the type-* utilities below, not text-sm and friends. */", "  --text-*: initial;");
out.push(decl("--font-sans", "var(--font-family-body)"));
out.push("}", "", "@theme {", "  --breakpoint-*: initial;");
for (const [path, t] of leaves(alias.breakpoint.width)) {
  if (slug(path[0]) === "mobile") continue; // mobile is the unprefixed base
  out.push(decl(`--breakpoint-${slug(path[0])}`, `${t.value}px`));
}
out.push("}", "");

// ── Composite type utilities: type-body-sm, type-heading-lg, … ───────────
for (const [name, family] of typeStyles) {
  out.push(
    `@utility type-${name} {`,
    decl("font-family", `var(--font-family-${family})`),
    decl("font-size", `var(--font-size-${name})`),
    decl("line-height", `var(--line-height-${name})`),
    decl("letter-spacing", `var(--letter-spacing-${name})`),
    "}",
  );
}
out.push("");

writeFileSync(resolve(root, "src/styles/tokens.css"), out.join("\n"));

// ── Token catalogue for the docs page ────────────────────────────────────
const px = (v) => {
  const m = /^\{([^}]+)\}$/.exec(String(v));
  if (!m) return Number(v);
  const node = m[1].split(".").reduce((n, k) => n[k], primitives);
  return node.value;
};
const semantic = {};
for (const [path, t] of leaves(light)) {
  const [group, name] = path.map(slug);
  const darkValue = path.reduce((n, k) => n[k], dark).value;
  (semantic[group] ??= []).push({ name, token: `${group}-${name}`, light: t.value, dark: darkValue });
}
const catalogue = {
  semantic,
  radius: [...leaves(alias.roundness)].map(([p, t]) => ({ name: slug(p[0]).replace(/^radius-/, ""), px: px(t.value) })),
  spacing: [...leaves(alias.spacing)].map(([p, t]) => ({ name: slug(p[0]).replace(/^spacing-/, ""), px: px(t.value) })),
  type: [...typeStyles].map(([name, family]) => ({
    name,
    family,
    size: px(typography["font size"][family][name.slice(family.length + 1)].value),
    lineHeight: px(typography["line height"][family][name.slice(family.length + 1)].value),
  })),
};
writeFileSync(
  resolve(root, "src/styles/tokens.generated.ts"),
  `// GENERATED by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit.\nexport const tokens = ${JSON.stringify(catalogue, null, 2)} as const;\n`,
);

console.log(`tokens: ${semanticNames.length} semantic colours, ${typeStyles.size} type styles`);
